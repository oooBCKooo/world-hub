export function translateDemoText(value, language = 'zh-CN', params = {}) {
  const source = String(value ?? '');
  const template = language === 'en' ? (EXPLORER_EN[source] ?? source) : source;
  return template.replace(/\{([\w]+)\}/g, (match, key) => Object.hasOwn(params, key) ? String(params[key]) : match);
}

// Only known demo output phrases are adapted. Unknown program text is displayed
// verbatim and all original payloads remain available in the raw response.
export function displayDemoOutput(value, language = 'zh-CN') {
  const text = String(value ?? '');
  if (language !== 'en') return text;
  const trade = /^交换 (\d+) 份补给恢复体力$/.exec(text);
  if (trade) return translateDemoText('交换 {quantity} 份补给恢复体力', language, { quantity: trade[1] });
  const integer = /^(.+?) 必须是 (-?\d+)–(-?\d+) 的整数$/.exec(text);
  if (integer) return translateDemoText('{field} 必须是 {minimum}–{maximum} 的整数', language, { field: integer[1], minimum: integer[2], maximum: integer[3] });
  const bounded = /^(.+?) 必须是 1–(\d+) 字节的非空文本$/.exec(text);
  if (bounded) return translateDemoText('{field} 必须是 1–{maximum} 字节的非空文本', language, { field: bounded[1], maximum: bounded[2] });
  const command = /^(?:(.+?) )?来源不支持命令：(.*)$/.exec(text);
  if (command) return translateDemoText(command[1] ? '{provider} 来源不支持命令：{command}' : '来源不支持命令：{command}', language, { provider: command[1], command: command[2] });
  const refusal = /^(.+?) 程序拒绝：(.*)$/s.exec(text);
  if (refusal) return translateDemoText('{provider} 程序拒绝：{error}', language, { provider: refusal[1], error: displayDemoOutput(refusal[2], language) });
  for (const source of ['上下文来源失败：', '外部执行器失败：']) {
    if (text.startsWith(source)) return translateDemoText(source + '{error}', language, { error: text.slice(source.length) });
  }
  return translateDemoText(text, language);
}
